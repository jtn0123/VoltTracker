  function normalize(/** @type {any} */ code) {
    return String(code || "")
      .toUpperCase()
      .trim();
  }

  // Falls back to a category description based on the SAE prefix, so an
  // unrecognised code still gets a useful hint (e.g. P03xx => Ignition/Misfire).
  function categoryHint(/** @type {any} */ code) {
    const key = normalize(code);
    if (!key || key.length < 4) return null;
    const head = key.charAt(0);
    const second = key.charAt(1);
    const hundreds = second + key.charAt(2);
    if (head === "P") {
      if (hundreds === "00") return "Fuel/air metering - auxiliary emission controls";
      if (hundreds === "01") return "Fuel/air metering";
      if (hundreds === "02") return "Fuel/air metering - injector circuit";
      if (hundreds === "03") return "Ignition system or misfire";
      if (hundreds === "04") return "Auxiliary emissions (catalyst, EVAP, EGR)";
      if (hundreds === "05") return "Vehicle speed / idle / auxiliary inputs";
      if (hundreds === "06") return "Computer / control-module output";
      if (hundreds === "07" || hundreds === "08" || hundreds === "09")
        return "Transmission";
      if (hundreds === "0A") return "Hybrid propulsion (drive motors / inverter)";
      if (hundreds === "0B") return "Hybrid battery / cell";
      if (hundreds === "0C" || hundreds === "0D") return "Hybrid charging / extension";
      if (second === "1") return "Manufacturer-specific powertrain (GM / Volt)";
      if (second === "2") return "Generic powertrain (extended SAE)";
      if (second === "3") return "Manufacturer-specific powertrain (extended)";
    }
    if (head === "B") return "Body / restraints code";
    if (head === "C") return "Chassis / ABS / brakes code";
    if (head === "U") return "Network / communication bus code";
    return null;
  }

  function dtcInfo(/** @type {any} */ code) {
    const key = normalize(code);
    /** @type {{ code: string, description: string | null, known: boolean, category: string | null, causes: any, severity: any }} */
    const empty = { code: "", description: null, known: false, category: null, causes: null, severity: null };
    if (!key) return empty;
    const desc = VOLT_DTC[key];
    const causesData = (VD.DTC_CAUSES && VD.DTC_CAUSES[key]) || null;
    const causes = causesData ? causesData.causes : null;
    const severity = causesData ? causesData.severity : null;
    const categoryTag = causesData ? causesData.category : null;
    if (desc) {
      return { code: key, description: desc, known: true, category: categoryTag, causes, severity };
    }
    return { code: key, description: null, known: false, category: categoryTag || categoryHint(key), causes, severity };
  }

  function dtcSearchUrl(/** @type {any} */ code) {
    const key = normalize(code);
    const q = encodeURIComponent((key || "OBD-II") + " Chevy Volt DTC");
    return "https://www.google.com/search?q=" + q;
  }

